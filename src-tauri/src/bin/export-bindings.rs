use std::{fs, path::PathBuf};

use inkflow_lib::model::{
    AssetPathRewrite, CheckpointRequest, DiskRevision, DocumentSnapshot, ExportOutcome,
    ExportRequest, ExternalChange, OpenTargetRequest, PreparedExportDestination,
    PreparedExportSource, RecoveryEntry, RecoverySnapshot, RecoveryWarning, RestoreOutcome,
    SaveDocumentRequest, SaveOutcome, SearchHit, SearchRequest, SessionTabV1, SessionV1,
    SettingsV1, WorkspaceEntry, WorkspaceSnapshot, WriteAssetRequest, WriteAssetResult,
};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let directory = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("src")
        .join("lib")
        .join("api")
        .join("generated");
    fs::create_dir_all(&directory)?;
    let config = Config::new()
        .with_out_dir(&directory)
        .with_large_int("number");

    DiskRevision::export_all(&config)?;
    OpenTargetRequest::export_all(&config)?;
    DocumentSnapshot::export_all(&config)?;
    SaveDocumentRequest::export_all(&config)?;
    SaveOutcome::export_all(&config)?;
    AssetPathRewrite::export_all(&config)?;
    ExternalChange::export_all(&config)?;
    WorkspaceEntry::export_all(&config)?;
    WorkspaceSnapshot::export_all(&config)?;
    SearchRequest::export_all(&config)?;
    SearchHit::export_all(&config)?;
    WriteAssetRequest::export_all(&config)?;
    WriteAssetResult::export_all(&config)?;
    ExportRequest::export_all(&config)?;
    ExportOutcome::export_all(&config)?;
    PreparedExportDestination::export_all(&config)?;
    PreparedExportSource::export_all(&config)?;
    RecoveryEntry::export_all(&config)?;
    RecoverySnapshot::export_all(&config)?;
    RecoveryWarning::export_all(&config)?;
    RestoreOutcome::export_all(&config)?;
    CheckpointRequest::export_all(&config)?;
    SettingsV1::export_all(&config)?;
    SessionTabV1::export_all(&config)?;
    SessionV1::export_all(&config)?;

    let exports = [
        "AssetPathRewrite",
        "CheckpointRequest",
        "DiskRevision",
        "DocumentSnapshot",
        "ExportOutcome",
        "ExportRequest",
        "ExternalChange",
        "OpenTargetRequest",
        "PreparedExportDestination",
        "PreparedExportSource",
        "RecoveryEntry",
        "RecoverySnapshot",
        "RecoveryWarning",
        "RestoreOutcome",
        "SaveDocumentRequest",
        "SaveOutcome",
        "SearchHit",
        "SearchRequest",
        "SettingsV1",
        "SessionTabV1",
        "SessionV1",
        "WorkspaceEntry",
        "WorkspaceSnapshot",
        "WriteAssetRequest",
        "WriteAssetResult",
    ]
    .into_iter()
    .map(|name| format!("export type {{ {name} }} from \"./{name}\";"))
    .collect::<Vec<_>>()
    .join("\n");
    fs::write(
        directory.join("index.ts"),
        format!("// Generated by ts-rs. Do not edit.\n{exports}\n"),
    )?;
    // ts-rs emits a trailing space before multiline field documentation.
    // Normalize generated output here so regenerating bindings stays clean.
    for entry in fs::read_dir(&directory)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            let source = fs::read_to_string(&path)?;
            let normalized = source
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n")
                + "\n";
            if normalized != source {
                fs::write(path, normalized)?;
            }
        }
    }
    Ok(())
}
